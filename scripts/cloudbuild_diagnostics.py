def evidence_code(error):
    if type(error) is EvidenceError and len(error.args) == 1 and type(error.args[0]) is str:
        if error.args[0] in SAFE_EVIDENCE_CODES:
            return error.args[0]
    return None

def phase(value):
    return value if type(value) is str and value in SAFE_PHASES else 'UNCLASSIFIED'
